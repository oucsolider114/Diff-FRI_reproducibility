"""S29: geometric audit of the OCMS one-parameter manifold vs the K-DOF fit.

Purpose
-------
Quantify what a one-parameter (OCMS-type) initialization can represent, on the
frozen evolving-SSP benchmark environment, without running any estimator:

  g_t      distance (max component) from the KRAKEN reference K-tuple to the
           OCMS manifold M_t = {k(xi1)} generated by Algorithm 1 of
           Li et al. (2026); also the L2 distance and the projection point.
  alpha_t  fraction of the frame-to-frame motion that is orthogonal to the
           tangent of M_t (1 - "how much of the motion a 1-D chart can follow").

The same geometry is applied to the tracker trajectory (csmt_k) to show whether
the estimator's own per-frame motion is chart-compatible.

Environment is rebuilt from configs/dynamic_local_basis_coupling_suite.json with
the canonical amplitude (4 m); eta(0) = 0.2743 m reproduces the archived
data/synthetic/frame_metrics.csv, which supplies the reference and estimate
trajectories.
"""
