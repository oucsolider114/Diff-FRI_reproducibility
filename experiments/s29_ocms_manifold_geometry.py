FREQ = 300.0
H = 40.0
DZ = 1.0
K = 3
OMEGA = 2.0 * math.pi * FREQ
DEPTHS = np.arange(0.0, H + 0.5 * DZ, DZ)
W = np.full(DEPTHS.size, DZ)
W[0] = W[-1] = 0.5 * DZ                      # trapezoid weights

CFG = json.loads((REPO / "configs" / "dynamic_local_basis_coupling_suite.json")
                 .read_text(encoding="utf-8"))
SSP_CFG = dict(CFG["ssp_dynamic"])
SSP_CFG["amplitude_m"] = 4.0                  # canonical amplitude


def reference_ssp(depths: np.ndarray, cfg: dict) -> np.ndarray:
    z = np.asarray(depths, float)
    cs, cd = float(cfg["surface_speed_m_s"]), float(cfg["deep_speed_m_s"])
    mb, tb = float(cfg["mixed_layer_bottom_m"]), float(cfg["thermocline_bottom_m"])
    c = np.empty_like(z)
    c[z <= mb] = cs
    mid = (z > mb) & (z <= tb)
    frac = (z[mid] - mb) / (tb - mb)
    c[mid] = cs + frac * (cd - cs)
    c[z > tb] = cd
    return c


def ssp_displacement(f: float, cfg: dict) -> float:
    amp = float(cfg["amplitude_m"])
    h = float(cfg.get("second_harmonic_fraction", 0.25))
    ph = float(cfg.get("second_harmonic_phase_rad", 0.35))
    raw = math.sin(2.0 * math.pi * f) + h * math.sin(4.0 * math.pi * f + ph)
    return amp * raw / (1.0 + abs(h))


def make_ssp(f: float) -> tuple[np.ndarray, float]:
    c0 = reference_ssp(DEPTHS, SSP_CFG["reference_profile"])
    eta = ssp_displacement(f, SSP_CFG)
    taper = np.exp(-0.5 * ((DEPTHS - float(SSP_CFG["center_depth_m"]))
                           / float(SSP_CFG["vertical_taper_sigma_m"])) ** 2)
    zd = np.clip(DEPTHS - eta * taper, DEPTHS[0], DEPTHS[-1])
    return np.interp(zd, DEPTHS, c0), eta


def mode_matrix(ks: np.ndarray, c: np.ndarray) -> np.ndarray:
    """Row-normalised trial mode functions for every candidate k (vectorised)."""
    q = (OMEGA / c) ** 2                        # (J,)
    k2 = np.asarray(ks, float) ** 2              # (Nk,)
    arg = q[None, :] - k2[:, None]               # (Nk, J)
    chi = np.where(arg >= 0.0, np.cos(DZ * np.sqrt(np.abs(arg))),
                   np.cosh(DZ * np.sqrt(np.abs(arg))))
    psi = np.zeros((ks.size, DEPTHS.size))
    if ks.size:
        psi[:, 1] = 1.0
        for j in range(1, DEPTHS.size - 1):
            psi[:, j + 1] = 2.0 * chi[:, j] * psi[:, j] - psi[:, j - 1]
    norm = np.sqrt(np.maximum(psi * psi @ W, 1e-300))
    return psi / norm[:, None]


def manifold(c: np.ndarray, xi_min: float, xi_max: float, n_grid: int = 600,
             max_modes: int = 16, prominence: float = 1e-3):
    """xi1 -> wavenumbers of mode orders 1..K of the OCMS orthogonality dictionary.

    Algorithm 1 of Li et al. (2026): from xi1, scan downward in xi and keep the
    local minima of |<psi(z,xi1), psi(z,xi)>|; label each survivor by its number
    of interior zero crossings (mode order) and keep orders 1..K.
    """
    xis = np.linspace(xi_min, xi_max, n_grid)
    P = mode_matrix(xis, c)
    pts, keep = [], []
    for i, xi1 in enumerate(xis):
        corr = np.abs(P @ (P[i] * W))
        pk, _ = find_peaks(-corr, prominence=prominence, distance=4)
        lab: dict[int, float] = {}
        for p in pk:
            if xis[p] >= xi1:            # scan downward from xi1 only
                continue
            if 0 < p < xis.size - 1:
                y0, y1, y2 = corr[p - 1], corr[p], corr[p + 1]
                den = y0 - 2.0 * y1 + y2
                d = 0.5 * (y0 - y2) / den if abs(den) > 1e-30 else 0.0
                x = float(xis[p] + d * (xis[p + 1] - xis[p]))
            else:
                x = float(xis[p])
            s = np.sign(P[p])
            nz = int(np.sum(s[1:] * s[:-1] < 0))
            lab.setdefault(nz + 1, x)
        s1 = np.sign(P[i])
        lab.setdefault(int(np.sum(s1[1:] * s1[:-1] < 0)) + 1, float(xi1))
        if all(o in lab for o in range(1, K + 1)):
            pts.append([lab[o] for o in range(1, K + 1)])
            keep.append(float(xi1))
    return np.array(keep), np.array(pts)


def project(points: np.ndarray, target: np.ndarray):
    """Index of the manifold point closest to target in L2."""
    d = np.linalg.norm(points - target[None, :], axis=1)
    i = int(np.argmin(d))
    return i, float(d[i])


def main() -> None:
    rows = list(csv.DictReader((REPO / "data" / "synthetic" / "frame_metrics.csv")
                               .open(encoding="utf-8-sig")))
    frames = sorted({int(r["time_index"]) for r in rows})
    by_rep = {}
    for r in rows:
        by_rep.setdefault(int(r["repeat"]), {})[int(r["time_index"])] = r

    # water-column admissible band of the letter (Eq. 5), evaluated on this profile
    c_max = float(np.max(reference_ssp(DEPTHS, SSP_CFG["reference_profile"])))
    c_min = float(np.min(reference_ssp(DEPTHS, SSP_CFG["reference_profile"])))
    xi_min, xi_max = 0.95 * OMEGA / c_max, 0.999999 * OMEGA / c_min

    out_rows = []
    kref_hist, alpha_tr, alpha_tk = [], [], []
    for t in frames:
        f = t / (len(frames) - 1)
        c, eta = make_ssp(f)
        xis, pts = manifold(c, xi_min, xi_max)
        kref = np.array([float(by_rep[0][t][f"kraken_k{m}"]) for m in (1, 2, 3)])[::-1]
        # match orientation: kraken_k1 > k2 > k3 already descending
        kref = np.array([float(by_rep[0][t][f"kraken_k{m}"]) for m in (1, 2, 3)])
        i, dl2 = project(pts, kref)
        g = float(np.max(np.abs(pts[i] - kref)))
        kref_hist.append(kref)

        # tangent at the projection, central difference on the manifold index
        if 0 < i < len(pts) - 1:
            tang = pts[i + 1] - pts[i - 1]
            jump = np.linalg.norm(pts[i + 1] - pts[i]) + np.linalg.norm(pts[i] - pts[i - 1])
            tang_ok = (np.linalg.norm(tang) > 0) and (jump < 0.1)
        else:
            tang, tang_ok = np.zeros(K), False

        out_rows.append(dict(frame=t, eta_m=eta, g_max=g, d_l2=dl2, xi_star=float(xis[i]),
                             tangent_ok=int(tang_ok),
                             k1=kref[0], k2=kref[1], k3=kref[2],
                             p1=pts[i][0], p2=pts[i][1], p3=pts[i][2],
                             full_err=float(np.mean([float(by_rep[r][t]["full_max_abs_error_rad_m"])
                                                     for r in by_rep]))))

    # ---- chart-following diagnostics (needs consecutive frames)
    for j in range(1, len(frames)):
        t0, t1 = frames[j - 1], frames[j]
        c, _ = make_ssp(t1 / (len(frames) - 1))
        xis, pts = manifold(c, xi_min, xi_max)
        dtruth = kref_hist[j] - kref_hist[j - 1]
        i, _ = project(pts, kref_hist[j])
        if 0 < i < len(pts) - 1:
            gvec = pts[i + 1] - pts[i - 1]
            gn = np.linalg.norm(gvec)
            if gn > 0:
                gh = gvec / gn
                orth = dtruth - (dtruth @ gh) * gh
                out_rows[j]["alpha_truth"] = float(np.linalg.norm(orth) / max(np.linalg.norm(dtruth), 1e-30))
        for rep, series in by_rep.items():
            est1 = np.array([float(series[t1][f"csmt_k{m}"]) for m in (1, 2, 3)])
            est0 = np.array([float(series[t0][f"csmt_k{m}"]) for m in (1, 2, 3)])
            d = est1 - est0
            ie, _ = project(pts, est1)
            if 0 < ie < len(pts) - 1:
                gv = pts[ie + 1] - pts[ie - 1]
                gn = np.linalg.norm(gv)
                if gn > 0:
                    gh = gv / gn
                    orth = d - (d @ gh) * gh
                    alpha_tk.append(float(np.linalg.norm(orth) / max(np.linalg.norm(d), 1e-30)))

    import os
    outdir = Path(os.environ.get("S29_OUT", str(Path(__file__).resolve().parent / "s29_ocms_manifold_geometry")))
    outdir.mkdir(parents=True, exist_ok=True)
    names: list[str] = []
    for r in out_rows:
        for key in r:
            if key not in names:
                names.append(key)
    with (outdir / "s29_manifold_geometry_frames.csv").open("w", newline="", encoding="utf-8-sig") as fh:
        w = csv.DictWriter(fh, fieldnames=names, restval="", extrasaction="ignore")
        w.writeheader(); w.writerows(out_rows)

    g = np.array([r["g_max"] for r in out_rows])
    dl2 = np.array([r["d_l2"] for r in out_rows])
    fe = np.array([r["full_err"] for r in out_rows])
    at = np.array([r["alpha_truth"] for r in out_rows if "alpha_truth" in r])
    summary = dict(
        frames=len(frames),
        g_max_median=float(np.median(g)), g_max_min=float(g.min()), g_max_max=float(g.max()),
        d_l2_median=float(np.median(dl2)),
        frac_g_le_criterion=float(np.mean(g <= 1.5e-3)),
        frac_g_le_2criterion=float(np.mean(g <= 3.0e-3)),
        full_err_median=float(np.median(fe)),
        ratio_g_over_full_err_median=float(np.median(g) / max(np.median(fe), 1e-30)),
        alpha_truth_median=float(np.median(at)) if at.size else None,
        alpha_truth_q25=float(np.quantile(at, 0.25)) if at.size else None,
        alpha_truth_q75=float(np.quantile(at, 0.75)) if at.size else None,
        alpha_track_median=float(np.median(alpha_tk)) if alpha_tk else None,
    )
    (outdir / "s29_manifold_geometry_summary.json").write_text(
        json.dumps(summary, indent=2), encoding="utf-8")
    print(json.dumps(summary, indent=2))
    for r in out_rows[:6]:
        print({k: (round(v, 6) if isinstance(v, float) else v) for k, v in r.items()})


if __name__ == "__main__":
    main()