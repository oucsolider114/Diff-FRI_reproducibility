"""Causal temporal-regularized modal-wavenumber refinement.

This module adds a *new* causal refinement layer on top of the existing
seabed-parameter-free instantaneous estimator.  It does not modify or replace
the frozen Top-N + Data-Gated Continuous Refinement implementation.

At time t the method uses:
    - current observation matrix Y(t);
    - current water-column metadata;
    - current instantaneous estimate k_inst(t);
    - previous accepted temporal estimates only.

It does NOT use:
    - seabed sound speed / density / attenuation;
    - physical roots;
    - KRAKEN truth;
    - future time samples.

The current instantaneous estimate remains the data-consistency fallback.
A temporal candidate is generated by warm-starting an exact-K ModeFRINET model
between the instantaneous estimate and a causal prediction, then minimizing

    L = L_data + lambda_t * Huber((k - k_prior) / sigma_t).

The temporal candidate is accepted only when its present-time projection
residual remains within predeclared data-only tolerances of the instantaneous
reference.  Otherwise the method falls back to k_inst(t).
"""

from __future__ import annotations

from dataclasses import dataclass
import math

import numpy as np
import torch
import torch.nn.functional as F

from mode_fri.mode_frinet import ModeFRINET
from mode_fri.mode_solver import solve_mode


GRADIENT_CLIP_NORM = 5.0
SEARCH_LOWER_FRACTION = 0.95
SEARCH_UPPER_FRACTION = 0.999999


@dataclass(frozen=True)
class TemporalRefinementConfig:
    initial_prior_blend: float = 0.50
    temporal_weight: float = 1.0e-3
    temporal_sigma_rad_m: float = 1.5e-3
    temporal_huber_delta: float = 1.0

    coefficient_warmup_steps: int = 100
    joint_refinement_steps: int = 400
    coefficient_warmup_lr: float = 1.0e-2
    coefficient_joint_lr: float = 2.0e-3
    wavenumber_joint_lr: float = 8.0e-5

    predictor_momentum: float = 0.50
    predictor_max_step_rad_m: float = 1.5e-3

    minimum_mode_separation_rad_m: float = 3.5e-3

    gate_mean_relative_tolerance: float = 5.0e-3
    gate_worst_relative_tolerance: float = 1.0e-2


@dataclass(frozen=True)
class TemporalRefinementResult:
    final_wavenumbers: np.ndarray
    temporal_candidate: np.ndarray
    prior_prediction: np.ndarray
    initialization: np.ndarray
    accepted: bool
    reference_scores: tuple[float, float]
    candidate_scores: tuple[float, float]
    temporal_deviation_rms_rad_m: float


@dataclass(frozen=True)
class _Validated:
    observations: np.ndarray
    receiver_depths: np.ndarray
    receiver_indices: np.ndarray
    sound_speed_profile: np.ndarray
    water_depth: float
    dz: float
    omega: float
    k_min: float
    k_max: float
    K: int
    seed: int


def _validate(
    Y: np.ndarray,
    K: int,
    frequency: float,
    array_geometry: np.ndarray,
    water_depth: float,
    SSP: np.ndarray,
    seed: int,
) -> _Validated:
    observations = np.asarray(Y, dtype=np.complex128)
    if observations.ndim != 2 or min(observations.shape) <= 0:
        raise ValueError("Y must be a non-empty [receivers, snapshots] matrix")
    if not np.all(np.isfinite(observations.real)) or not np.all(
        np.isfinite(observations.imag)
    ):
        raise ValueError("Y contains non-finite values")

    K = int(K)
    if K <= 0:
        raise ValueError("K must be positive")

    frequency = float(frequency)
    water_depth = float(water_depth)
    if frequency <= 0.0 or water_depth <= 0.0:
        raise ValueError("frequency and water_depth must be positive")

    receiver_depths = np.asarray(array_geometry, dtype=np.float64).reshape(-1)
    if receiver_depths.size != observations.shape[0]:
        raise ValueError("array_geometry must contain one depth per receiver")

    sound_speed = np.asarray(SSP, dtype=np.float64).reshape(-1)
    if sound_speed.size < 3 or np.any(sound_speed <= 0.0):
        raise ValueError("SSP must contain at least three positive values")

    dz = water_depth / float(sound_speed.size - 1)
    receiver_indices = np.rint(receiver_depths / dz).astype(np.int64)
    grid = np.linspace(0.0, water_depth, sound_speed.size, dtype=np.float64)

    if np.any(receiver_indices < 0) or np.any(receiver_indices >= sound_speed.size):
        raise ValueError("receiver depth lies outside water column")
    if not np.allclose(
        grid[receiver_indices],
        receiver_depths,
        rtol=0.0,
        atol=max(1.0e-9, dz * 1.0e-7),
    ):
        raise ValueError("receiver depths must align with the SSP grid")

    omega = 2.0 * math.pi * frequency
    k_min = SEARCH_LOWER_FRACTION * omega / float(np.max(sound_speed))
    k_max = SEARCH_UPPER_FRACTION * omega / float(np.min(sound_speed))
    if not (0.0 < k_min < k_max):
        raise ValueError("invalid water-column wavenumber interval")

    return _Validated(
        observations=observations.copy(),
        receiver_depths=receiver_depths.copy(),
        receiver_indices=receiver_indices,
        sound_speed_profile=sound_speed.copy(),
        water_depth=water_depth,
        dz=dz,
        omega=omega,
        k_min=k_min,
        k_max=k_max,
        K=K,
        seed=int(seed),
    )


def _project_descending(
    values: np.ndarray,
    k_min: float,
    k_max: float,
    minimum_separation: float,
) -> np.ndarray:
    x = np.sort(np.asarray(values, dtype=np.float64).reshape(-1))[::-1].copy()
    x = np.clip(x, float(k_min), float(k_max))
    sep = max(float(minimum_separation), 0.0)

    if x.size <= 1 or sep <= 0.0:
        return x

    # Small-K deterministic adjacent projection.
    for _ in range(8 * x.size):
        changed = False
        for i in range(x.size - 1):
            if x[i] - x[i + 1] < sep:
                center = 0.5 * (x[i] + x[i + 1])
                x[i] = center + 0.5 * sep
                x[i + 1] = center - 0.5 * sep
                changed = True
        x = np.clip(x, float(k_min), float(k_max))
        if not changed:
            break

    return np.sort(x)[::-1].copy()


def predict_causal_prior(
    previous_wavenumbers: np.ndarray,
    previous_previous_wavenumbers: np.ndarray | None,
    *,
    k_min: float,
    k_max: float,
    config: TemporalRefinementConfig,
) -> np.ndarray:
    previous = np.sort(
        np.asarray(previous_wavenumbers, dtype=np.float64).reshape(-1)
    )[::-1].copy()

    if previous_previous_wavenumbers is None:
        prediction = previous.copy()
    else:
        older = np.sort(
            np.asarray(previous_previous_wavenumbers, dtype=np.float64).reshape(-1)
        )[::-1].copy()
        if older.shape != previous.shape:
            raise ValueError("previous estimates must have the same shape")

        delta = float(config.predictor_momentum) * (previous - older)
        max_step = float(config.predictor_max_step_rad_m)
        delta = np.clip(delta, -max_step, max_step)
        prediction = previous + delta

    return _project_descending(
        prediction,
        k_min,
        k_max,
        config.minimum_mode_separation_rad_m,
    )


def _normalized_observations(inputs: _Validated) -> torch.Tensor:
    y = torch.as_tensor(
        inputs.observations,
        dtype=torch.complex128,
        device=torch.device("cpu"),
    )
    scale = torch.sqrt(torch.mean(torch.abs(y) ** 2)).clamp_min(1.0e-14)
    return y / scale


def _sampled_mode_basis(inputs: _Validated, wavenumbers: np.ndarray) -> np.ndarray:
    columns: list[np.ndarray] = []
    for k in np.asarray(wavenumbers, dtype=np.float64).reshape(-1):
        full = solve_mode(
            horizontal_wavenumber=float(k),
            omega=float(inputs.omega),
            sound_speed_profile=inputs.sound_speed_profile,
            dz=float(inputs.dz),
        )
        sampled = np.asarray(full[inputs.receiver_indices], dtype=np.complex128)
        norm = max(float(np.linalg.norm(sampled)), 1.0e-14)
        sampled = sampled / norm
        columns.append(sampled)
    return np.column_stack(columns).astype(np.complex128)


def projection_scores(
    inputs: _Validated,
    wavenumbers: np.ndarray,
) -> tuple[float, float]:
    basis = _sampled_mode_basis(inputs, wavenumbers)
    coefficients, _, _, _ = np.linalg.lstsq(
        basis,
        inputs.observations,
        rcond=None,
    )
    residual = inputs.observations - basis @ coefficients

    snapshot_energy = np.sum(np.abs(inputs.observations) ** 2, axis=0)
    residual_energy = np.sum(np.abs(residual) ** 2, axis=0)
    normalized = residual_energy / np.maximum(snapshot_energy, 1.0e-30)
    return float(np.mean(normalized)), float(np.max(normalized))


def _is_separated(values: np.ndarray, minimum_separation: float) -> bool:
    x = np.sort(np.asarray(values, dtype=np.float64).reshape(-1))[::-1].copy()
    if x.size <= 1:
        return True
    return bool(
        np.all(
            (x[:-1] - x[1:])
            >= float(minimum_separation) - 1.0e-12
        )
    )


def estimate_temporally_regularized(
    Y: np.ndarray,
    K: int,
    frequency: float,
    array_geometry: np.ndarray,
    water_depth: float,
    SSP: np.ndarray,
    seed: int,
    instantaneous_wavenumbers: np.ndarray,
    previous_temporal_wavenumbers: np.ndarray,
    previous_previous_temporal_wavenumbers: np.ndarray | None = None,
    config: TemporalRefinementConfig | None = None,
) -> TemporalRefinementResult:
    """Causally refine the current instantaneous estimate with a temporal prior."""

    cfg = config or TemporalRefinementConfig()
    inputs = _validate(
        Y,
        K,
        frequency,
        array_geometry,
        water_depth,
        SSP,
        seed,
    )

    instant = _project_descending(
        instantaneous_wavenumbers,
        inputs.k_min,
        inputs.k_max,
        cfg.minimum_mode_separation_rad_m,
    )
    if instant.size != inputs.K:
        raise ValueError("instantaneous_wavenumbers must contain exactly K values")

    prior = predict_causal_prior(
        previous_temporal_wavenumbers,
        previous_previous_temporal_wavenumbers,
        k_min=inputs.k_min,
        k_max=inputs.k_max,
        config=cfg,
    )
    if prior.size != inputs.K:
        raise ValueError("previous temporal estimate must contain exactly K values")

    blend = float(cfg.initial_prior_blend)
    if not 0.0 <= blend <= 1.0:
        raise ValueError("initial_prior_blend must be in [0, 1]")

    initialization = _project_descending(
        (1.0 - blend) * instant + blend * prior,
        inputs.k_min,
        inputs.k_max,
        cfg.minimum_mode_separation_rad_m,
    )

    np.random.seed(inputs.seed)
    torch.manual_seed(inputs.seed)

    model = ModeFRINET(
        number_of_atoms=inputs.K,
        number_of_snapshots=inputs.observations.shape[1],
        k_min=inputs.k_min,
        k_max=inputs.k_max,
        omega=inputs.omega,
        sound_speed_profile=torch.as_tensor(
            inputs.sound_speed_profile,
            dtype=torch.float64,
            device=torch.device("cpu"),
        ),
        dz=inputs.dz,
        random_seed=inputs.seed,
        initial_wavenumbers=np.ascontiguousarray(initialization, dtype=np.float64),
        initialization_bandwidth=0.0,
        bottom_config=None,
    ).to(torch.device("cpu"))

    normalized_y = _normalized_observations(inputs)
    receiver_indices = torch.as_tensor(
        inputs.receiver_indices,
        dtype=torch.long,
        device=torch.device("cpu"),
    )
    prior_tensor = torch.as_tensor(
        np.ascontiguousarray(prior, dtype=np.float64),
        dtype=torch.float64,
        device=torch.device("cpu"),
    )

    # Stage 1: present-time coefficient fit with k fixed.
    model.k_raw.requires_grad_(False)
    coefficient_optimizer = torch.optim.Adam(
        [model.coefficient_real, model.coefficient_imag],
        lr=float(cfg.coefficient_warmup_lr),
    )

    for _ in range(int(cfg.coefficient_warmup_steps)):
        coefficient_optimizer.zero_grad()
        output = model()
        reconstruction = output.reconstruction.index_select(
            0, receiver_indices
        )
        fit_loss = torch.mean(torch.abs(reconstruction - normalized_y) ** 2)
        if not torch.isfinite(fit_loss):
            raise FloatingPointError(
                "temporal coefficient warmup produced a non-finite loss"
            )
        fit_loss.backward()
        torch.nn.utils.clip_grad_norm_(
            [model.coefficient_real, model.coefficient_imag],
            GRADIENT_CLIP_NORM,
        )
        coefficient_optimizer.step()

    # Stage 2: present-time data fit + robust causal temporal consistency.
    model.k_raw.requires_grad_(True)
    optimizer = torch.optim.Adam(
        [
            {
                "params": [model.k_raw],
                "lr": float(cfg.wavenumber_joint_lr),
            },
            {
                "params": [
                    model.coefficient_real,
                    model.coefficient_imag,
                ],
                "lr": float(cfg.coefficient_joint_lr),
            },
        ]
    )

    sigma = max(float(cfg.temporal_sigma_rad_m), 1.0e-12)
    temporal_weight = float(cfg.temporal_weight)

    for _ in range(int(cfg.joint_refinement_steps)):
        optimizer.zero_grad()

        output = model()
        reconstruction = output.reconstruction.index_select(
            0, receiver_indices
        )
        fit_loss = torch.mean(torch.abs(reconstruction - normalized_y) ** 2)

        sorted_k = torch.sort(
            model.get_wavenumbers(),
            descending=True,
        ).values
        normalized_deviation = (sorted_k - prior_tensor) / sigma

        temporal_loss = F.huber_loss(
            normalized_deviation,
            torch.zeros_like(normalized_deviation),
            reduction="mean",
            delta=float(cfg.temporal_huber_delta),
        )
        total_loss = fit_loss + temporal_weight * temporal_loss

        if not torch.isfinite(total_loss):
            raise FloatingPointError(
                "temporal joint refinement produced a non-finite loss"
            )

        total_loss.backward()
        torch.nn.utils.clip_grad_norm_(
            model.parameters(),
            GRADIENT_CLIP_NORM,
        )
        optimizer.step()

    model.eval()
    with torch.no_grad():
        candidate = (
            torch.sort(model.get_wavenumbers(), descending=True)
            .values.detach()
            .cpu()
            .numpy()
            .astype(np.float64)
        )

    candidate = np.clip(candidate, inputs.k_min, inputs.k_max)

    reference_scores = projection_scores(inputs, instant)
    candidate_scores = projection_scores(inputs, candidate)

    separated = _is_separated(
        candidate,
        cfg.minimum_mode_separation_rad_m,
    )

    accepted = (
        separated
        and candidate_scores[0]
        <= reference_scores[0]
        * (1.0 + float(cfg.gate_mean_relative_tolerance))
        and candidate_scores[1]
        <= reference_scores[1]
        * (1.0 + float(cfg.gate_worst_relative_tolerance))
    )

    final = candidate if accepted else instant

    return TemporalRefinementResult(
        final_wavenumbers=np.sort(final)[::-1].copy(),
        temporal_candidate=np.sort(candidate)[::-1].copy(),
        prior_prediction=np.sort(prior)[::-1].copy(),
        initialization=np.sort(initialization)[::-1].copy(),
        accepted=bool(accepted),
        reference_scores=reference_scores,
        candidate_scores=candidate_scores,
        temporal_deviation_rms_rad_m=float(
            np.sqrt(np.mean((candidate - prior) ** 2))
        ),
    )
